register cron_two_projects_coexist
case_cron_two_projects_coexist() {
  new_project "$CASE_DIR/alpha"
  local a=$CRON
  new_project "$CASE_DIR/beta"
  local b=$CRON
  seed_crontab
  try cron_sh "$a/install.sh"
  expect_rc 0 "装 alpha"
  try cron_sh "$b/install.sh"
  expect_rc 0 "装 beta"
  expect_eq "$(block_count ALPHA)/$(block_count BETA)" 1/1 "两个区块各一份"
  local beta_block
  beta_block=$(awk '$0 == "# >>> CRON:BETA >>>" { p = 1 } p { print } $0 == "# <<< CRON:BETA <<<" { p = 0 }' "$(crontab_file)")
