register cron_dry_run_does_not_write
case_cron_dry_run_does_not_write() {
  new_project "$CASE_DIR/my-app"
  seed_crontab
  local before root
  before=$(crontab_sum)
  root=$(phys "$CASE_DIR/my-app")
  try cron_sh "$CRON/install.sh" --dry-run
  expect_rc 0 "dry-run"
  expect_out "# >>> CRON:MY_APP >>>"
  expect_out "# $root"
  expect_out "*/5 * * * * cd \"$root\" && { echo hi ; } >> \"$root/logs/cron/cron.log\" 2>&1"
  expect_out "# <<< CRON:MY_APP <<<"
  expect_eq "$(crontab_sum)" "$before" "dry-run 不写 crontab"
  [ ! -e "$root/logs" ] || fail "dry-run 不应建日志目录"
}

