  expect_eq "$(block_count ALPHA)" 0 "alpha 的区块已删"
  expect_eq "$(awk '$0 == "# >>> CRON:BETA >>>" { p = 1 } p { print } $0 == "# <<< CRON:BETA <<<" { p = 0 }' "$(crontab_file)")" \
    "$beta_block" "beta 的区块原样保留"
  expect_eq "$(crontab_text | head -n 3)" "$OTHER_JOBS" "原有内容保留"
}

# ---------------------------------------------------------------------------
# 标记撞车与接管

# 撞车时 install、uninstall、dry-run 都报错退出 1，对方的区块不变。
expect_collision() { # expect_collision <install.sh 所在目录> <标记> <对方项目根>
  local dir=$1 tag=$2 owner=$3 before cmd
  before=$(crontab_sum)
  for cmd in "install.sh" "install.sh --dry-run" "uninstall.sh"; do
    # shellcheck disable=SC2086
    try cron_sh "$dir/"$cmd
    expect_rc 1 "撞车时 $cmd"
    expect_out "标记 $tag 已被 $owner 使用" "撞车时 $cmd"
    expect_eq "$(crontab_sum)" "$before" "撞车时 $cmd 不动 crontab"
  done
  expect_eq "$(block_count "$tag")" 1 "对方的区块仍是一份"
  expect_eq "$(block_owner "$tag")" "$owner" "区块仍记着对方的项目根"
}

