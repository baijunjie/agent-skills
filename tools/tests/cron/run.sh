register cron_collision_fixed_tag_resolves
case_cron_collision_fixed_tag_resolves() {
  new_project "$CASE_DIR/p1/my-app"
  local a=$CRON
  new_project "$CASE_DIR/p2/my-app"
  local b=$CRON
  try cron_sh "$a/install.sh"
  expect_rc 0 "装 p1/my-app"
  # 按 common.sh 的说明改成固定标记后不再撞车
  sed 's/^CRON_TAG=\${CRON_TAG:-\$(default_tag)}$/CRON_TAG=${CRON_TAG:-MY_APP_TWO}/' "$b/common.sh" >"$b/common.sh.new"
  mv "$b/common.sh.new" "$b/common.sh"
  grep -q 'MY_APP_TWO' "$b/common.sh" || fail "没改到 common.sh 的 CRON_TAG 默认值"
  try cron_sh "$b/install.sh"
  expect_rc 0 "改成固定标记后安装"
  expect_eq "$(block_count MY_APP)/$(block_count MY_APP_TWO)" 1/1 "两个区块各一份"
}

