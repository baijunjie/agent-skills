#!/usr/bin/env bash
# setup-tools:cron 装出的 crontab 安装脚本（plugins/setup-tools/skills/cron/template/cron/）的测试。
#   bash tools/tests/cron/run.sh [-v] [<用例名>...]
# 环境变量 CRON_TEMPLATE_DIR 可指向另一份 cron 模板目录（如故意改坏的副本），默认测仓库里的那份。
#
# 绝不碰真实 crontab：被测脚本一律经 env -i 运行，PATH 只含自建的 bin 目录——里面是必需工具的软链，
# 外加一个读写 $FAKE_CRONTAB 文件的假 crontab；另一份 bin 不含 crontab，测「没有 crontab 命令」。
# 两份 bin 建好后先核对：前者的 crontab 是那个假脚本，后者没有 crontab，任一不符整套不跑。
#
# 每个用例在自己的目录里放项目：<项目根>/scripts/cron/ 下是模板的四个文件（即模板默认的深度），
# tasks.conf 界线行之后追加一个任务。

source "$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)/lib/common.sh"

CRON_SRC=${CRON_TEMPLATE_DIR:-$REPO_ROOT/plugins/setup-tools/skills/cron/template/cron}
CRON_SRC=$(cd "$CRON_SRC" && pwd -P)
for f in common.sh install.sh uninstall.sh tasks.conf; do
  [ -f "$CRON_SRC/$f" ] || die "找不到 cron 模板文件：$CRON_SRC/$f"
done

SNAP_BEFORE=$(repo_snapshot)
make_tmp

# ---------------------------------------------------------------------------
# 自建 bin 与假 crontab

BIN_NOCRON=$T/cronbin-nocron
BIN_CRON=$T/cronbin
mkdir -p "$BIN_NOCRON" "$BIN_CRON"
for tool in sh awk sed tr cksum cut find head date wc basename dirname mkdir uname cat rm grep; do
  p=$(type -P "$tool") || die "找不到必需的工具：$tool"
  ln -s "$p" "$BIN_NOCRON/$tool"
  ln -s "$p" "$BIN_CRON/$tool"
done
cat >"$BIN_CRON/crontab" <<'EOF'
#!/bin/sh
# 假 crontab：内容存在 $FAKE_CRONTAB 文件里，只支持 install.sh / uninstall.sh 用到的 -l、-r、-。
f=${FAKE_CRONTAB:?FAKE_CRONTAB 未设置}
case "${1:-}" in
  -l) [ -f "$f" ] || { echo "crontab: no crontab for tester" >&2; exit 1; }; cat "$f" ;;
  -r) [ -f "$f" ] || { echo "crontab: no crontab for tester" >&2; exit 1; }; rm -f "$f" ;;
  -) cat >"$f" ;;
  *) echo "fake crontab: 不支持的参数 $*" >&2; exit 2 ;;
esac
EOF
chmod +x "$BIN_CRON/crontab"
# 安全核对：有 crontab 的那份解析到的是假脚本，另一份解析不到 crontab。
[ "$(env -i PATH="$BIN_CRON" "$BIN_CRON/sh" -c 'command -v crontab')" = "$BIN_CRON/crontab" ] \
  || die "安全检查失败：自建 bin 里的 crontab 不是假脚本"
[ ! -L "$BIN_CRON/crontab" ] || die "安全检查失败：假 crontab 不能是软链"
if env -i PATH="$BIN_NOCRON" "$BIN_NOCRON/sh" -c 'command -v crontab' >/dev/null 2>&1; then
  die "安全检查失败：不含 crontab 的 bin 里解析到了 crontab"
fi

# ---------------------------------------------------------------------------
# 夹具与小工具

# 每个用例自己的假 crontab 文件。
crontab_file() { echo "$CASE_DIR/crontab"; }

# 运行被测脚本：cron_sh [--nocron] [--env K=V]... <脚本路径> [参数]...
# 环境只有 PATH、HOME、LC_ALL（默认 C，可用 --env 覆盖）、FAKE_CRONTAB 与 --env 给的变量。
cron_sh() {
  local bin=$BIN_CRON envs=()
  while [ $# -gt 0 ]; do
    case $1 in
      --nocron) bin=$BIN_NOCRON ;;
      --env) envs+=("$2"); shift ;;
      *) break ;;
    esac
    shift
  done
  run_at "$CASE_DIR" env -i PATH="$bin" HOME="$HOME" LC_ALL=C FAKE_CRONTAB="$(crontab_file)" \
    ${envs[@]+"${envs[@]}"} "$bin/sh" "$@"
}

# 建项目：new_project <项目根> [<脚本目录，相对项目根，默认 scripts>]，脚本目录写入 CRON。
new_project() {
  local root=$1 sub=${2:-scripts}
  CRON=$root/$sub/cron
  mkdir -p "$CRON"
  cp "$CRON_SRC/"* "$CRON/"
  printf '%s\n' "测试任务 | */5 * * * * | echo hi" >>"$CRON/tasks.conf"
}

phys() { (cd "$1" && pwd -P); }

crontab_text() { cat "$(crontab_file)" 2>/dev/null || true; }

# crontab 里某个标记的区块个数。
block_count() { # block_count <标记>
  local n
  n=$(grep -cxF "# >>> CRON:$1 >>>" "$(crontab_file)" 2>/dev/null) || true
  echo "${n:-0}"
}

# 某个标记的区块第二行记着的项目根。
block_owner() { # block_owner <标记>
  awk -v s="# >>> CRON:$1 >>>" 'hit { sub(/^# /, ""); print; exit } $0 == s { hit = 1 }' "$(crontab_file)"
}

# 去掉区块里带时间戳的那一行，用于比较两次安装的结果。
without_timestamp() { grep -v '^# generated by install.sh at ' || true; }

OTHER_JOBS='MAILTO=""
0 0 * * * /usr/local/bin/other-job --daily
# 别的工具写的注释'

seed_crontab() { printf '%s\n' "$OTHER_JOBS" >"$(crontab_file)"; }

crontab_sum() { cksum <"$(crontab_file)" 2>/dev/null || echo none; }

# 从 dry-run 的首行取标记。
dry_run_tag() { # dry_run_tag [cron_sh 的选项]... <install.sh>
  local out
  out=$(cron_sh "$@" --dry-run) || return 1
  printf '%s\n' "$out" | head -n 1 | sed -n 's/^# >>> CRON:\(.*\) >>>$/\1/p'
}

