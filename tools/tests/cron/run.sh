register cron_tag_ascii_names
case_cron_tag_ascii_names() {
  local pair name want got
  for pair in "my-app=MY_APP" "My.App2=MY_APP2" "a b=A_B" "x_9=X_9"; do
    name=${pair%%=*}
    want=${pair#*=}
    new_project "$CASE_DIR/$name"
    got=$(dry_run_tag "$CRON/install.sh")
    expect_eq "$got" "$want" "目录名 $name 的标记"
  done
}

register cron_tag_non_ascii_locale_independent
case_cron_tag_non_ascii_locale_independent() {
  local name root want c utf8 zh
  for name in "项目" "项目2" "my项目" "---" "café"; do
    new_project "$CASE_DIR/$name"
    root=$(phys "$CASE_DIR/$name")
    want=P$(printf '%s' "$root" | cksum | cut -d' ' -f1)
    c=$(dry_run_tag "$CRON/install.sh")
    utf8=$(dry_run_tag --env LC_ALL=en_US.UTF-8 "$CRON/install.sh")
    zh=$(dry_run_tag --env LC_ALL=zh_CN.UTF-8 "$CRON/install.sh")
    expect_eq "$c" "$want" "目录名 $name 在 C locale 下的标记"
    expect_eq "$utf8" "$want" "目录名 $name 在 en_US.UTF-8 下的标记"
    expect_eq "$zh" "$want" "目录名 $name 在 zh_CN.UTF-8 下的标记"
  done
  # 按一种 locale 装、另一种 locale 重装与卸载，仍是同一个区块
  new_project "$CASE_DIR/中文项目"
  try cron_sh "$CRON/install.sh"
  expect_rc 0 "C locale 安装"
  try cron_sh --env LC_ALL=en_US.UTF-8 "$CRON/install.sh"
  expect_rc 0 "UTF-8 locale 重装"
  expect_eq "$(grep -c '^# >>> CRON:' "$(crontab_file)")" 1 "两种 locale 下是同一个区块"
  try cron_sh --env LC_ALL=zh_CN.UTF-8 "$CRON/uninstall.sh"
  expect_rc 0 "另一种 locale 卸载"
  [ ! -e "$(crontab_file)" ] || fail "卸载后应不剩区块"
}

