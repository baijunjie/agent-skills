  try cron_sh "$CRON/install.sh" --dry-run
  expect_rc 1 "没有分隔符"
  expect_out "缺少命令"
  [ ! -e "$(crontab_file)" ] || fail "清单有错时不应写出 crontab"
}

# 命令字段里的 % 都要转义（crontab 把未转义的 % 当作换行）：项目根、单独设置的 CRON_LOG_DIR、
# 带偏移的 sleep 行都算；区块里的注释行与 PATH= 行不是命令，原样保留。
has_line() { printf '%s\n' "$OUT" | grep -qxF -- "$1" || fail "${2:-输出}里应有整行：$1"; }
register cron_percent_escaped
case_cron_percent_escaped() {
  local root esc pbin logdir elog
  # 项目根含 %，PATH 也含 %（经软链指向自建 bin）
  ln -s "$BIN_CRON" "$CASE_DIR/b%in"
  new_project "$CASE_DIR/100%app"
  root=$(phys "$CASE_DIR/100%app")
  esc=${root//%/\\%}
  try cron_sh --env PATH="$CASE_DIR/b%in" "$CRON/install.sh" --dry-run
  expect_rc 0 "项目根含 % 时 dry-run"
  has_line "*/5 * * * * cd \"$esc\" && { echo hi ; } >> \"$esc/logs/cron/cron.log\" 2>&1" "项目根含 % 时"
  has_line "# $root" "注释行"
  has_line "PATH=$CASE_DIR/b%in" "PATH 行"
  expect_not_out "cd \"$root\""

  # 项目根不含 %，只有 CRON_LOG_DIR 含 %；带偏移的任务每条 sleep 行都要转义
  new_project "$CASE_DIR/plain-app"
  printf '%s\n' "偏移任务 | */5 * * * * +0,30 | echo off" >>"$CRON/tasks.conf"
  root=$(phys "$CASE_DIR/plain-app")
  logdir="$CASE_DIR/log%dir"
  elog=${logdir//%/\\%}/cron.log
  try cron_sh --env CRON_LOG_DIR="$logdir" "$CRON/install.sh" --dry-run
  expect_rc 0 "CRON_LOG_DIR 含 % 时 dry-run"
  has_line "*/5 * * * * cd \"$root\" && { echo hi ; } >> \"$elog\" 2>&1" "CRON_LOG_DIR 含 % 时"
  has_line "*/5 * * * * cd \"$root\" && { echo off ; } >> \"$elog\" 2>&1" "偏移 +0 那行"
  has_line "*/5 * * * * sleep 30 && cd \"$root\" && { echo off ; } >> \"$elog\" 2>&1" "偏移 sleep 那行"
  has_line "# $root" "注释行"
  expect_not_out "$logdir/cron.log"
}

