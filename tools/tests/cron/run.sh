register cron_tasks_conf_boundary
case_cron_tasks_conf_boundary() {
  new_project "$CASE_DIR/my-app"
  local root
  root=$(phys "$CASE_DIR/my-app")
  # 界线行之前已启用的任务行（用户直接把示例改成了启用）与界线行之后的内容都要读到；注释与空行忽略。
  # 界线行之后整段换成下面这些（夹具追加的任务不要了）
  python3 - "$CRON/tasks.conf" <<'EOF'
import sys
from pathlib import Path
p = Path(sys.argv[1])
s = p.read_text(encoding="utf-8")
boundary = "# ---- 本项目的任务写在这一行之后 ----\n"
assert s.count(boundary) == 1, "tasks.conf 的界线行变了"
before, after = s.split(boundary)
before = before.replace("# 每日备份      | 0 3 * * *            | ./scripts/backup.sh --retention 7",
                        "每日备份      | 0 3 * * *            | ./scripts/backup.sh --retention 7")
assert "\n每日备份 " in before, "示例行变了"
after = "\n".join([
    "",
    "# 停用的任务 | * * * * * | echo disabled",
    "   ",
    "  高频巡检 | * * * * * +0,20 | node poll.js | tee -a out.log",
    "百分号 | @daily | date +%Y%m%d",
    "末行无换行 | 0 1 * * * | echo last",
])
p.write_text(before + boundary + after, encoding="utf-8")
EOF
  try cron_sh "$CRON/install.sh" --dry-run
  expect_rc 0 "dry-run"
  local body="cd \"$root\" && {"
  local log=">> \"$root/logs/cron/cron.log\" 2>&1"
  expect_out "# 每日备份"
  expect_out "0 3 * * * $body ./scripts/backup.sh --retention 7 ; } $log"
  expect_out "* * * * * $body node poll.js | tee -a out.log ; } $log"
  expect_out "* * * * * sleep 20 && $body node poll.js | tee -a out.log ; } $log"
  expect_out "@daily $body date +\\%Y\\%m\\%d ; } $log"
  expect_out "0 1 * * * $body echo last ; } $log"
  expect_not_out "echo disabled"
  expect_not_out "sleep 0"
  expect_not_out "同步数据"
  # 顺序：界线行之前的在前，之后的按原顺序
  local order
  order=$(printf '%s\n' "$OUT" | grep -E '^# (每日备份|高频巡检|百分号|末行无换行)$' | sed 's/^# //' | tr '\n' ' ')
  expect_eq "$order" "每日备份 高频巡检 百分号 末行无换行 " "任务顺序"
  try cron_sh "$CRON/install.sh"
  expect_rc 0 "安装"
  expect_out "  - 每日备份  (0 3 * * *)"
  expect_out "  - 高频巡检  (* * * * * +0,20)"
}

register cron_tasks_conf_errors
