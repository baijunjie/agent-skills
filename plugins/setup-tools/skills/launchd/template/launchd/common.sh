#!/bin/sh
#
# install.sh / uninstall.sh / status.sh 的公共部分：定位项目、算 LaunchAgent 标签、
# 读写 ~/Library/LaunchAgents。
#
# 为什么是 LaunchAgent 而不是 cron：cron 的进程不在用户的 GUI（Aqua）会话里，读 login keychain 会得到
# “User interaction is not allowed”，要登录态的命令行工具与 headful 的浏览器因此都起不来；用户级
# LaunchAgent 跑在 gui/<uid> 域里，这两件事才成立。代价是它跟着登录会话：注销或关机期间不跑，
# 重新登录后自动加载。
#
set -euf   # -f 关掉通配：cron 字段里的 * 必须按字面走词拆分，不能被当成文件名通配

# 都取物理路径：经软链访问同一项目时，标签与 plist 里记的项目根才不会随访问路径变。
SCRIPT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd -P)

# 下面 PROJECT_ROOT、LOG_DIR、LABEL_PREFIX 三个默认值按项目定，要长期生效就直接改默认值；
# 对应的环境变量（LAUNCHD_PROJECT_ROOT、LAUNCHD_LOG_DIR、LAUNCHD_LABEL_PREFIX）只用于临时覆盖，
# 靠它的话每次 install / uninstall 都得带上同一组。

# 项目根目录：默认取脚本目录上溯两级，对应脚本在 <项目根>/<一级目录>/launchd/ 下；深度不同时改层级。
PROJECT_ROOT=${LAUNCHD_PROJECT_ROOT:-$(CDPATH= cd -- "$SCRIPT_DIR/../.." && pwd -P)}

TASKS_FILE=${LAUNCHD_TASKS_FILE:-$SCRIPT_DIR/tasks.conf}

# 日志目录：默认 <项目根>/logs/launchd；项目已有约定的日志目录时改成它。
LOG_DIR=${LAUNCHD_LOG_DIR:-$PROJECT_ROOT/logs/launchd}
LOG_FILE=$LOG_DIR/launchd.log

# 标签前缀：同一台机器上多个项目靠它互不干扰，也是认出哪些 plist 是本项目装的唯一依据。
# 默认由项目根目录名归一化得出；目录名含非 ASCII 字符（如中文名）或没有字母数字时改用项目根路径的
# cksum——非 ASCII 字符按 locale 折算成的 `-` 个数不定，同一目录在不同终端会算出不同前缀。cksum 随
# 路径变，项目移动后旧 plist 会留在 ~/Library/LaunchAgents 里，所以这种项目要把下面的默认值改成固定
# 前缀。不同路径的同名项目、归一化后相同的目录名（my-app 与 my_app）会撞车，install.sh / uninstall.sh
# 会报错退出，同样改成固定前缀：LABEL_PREFIX=${LAUNCHD_LABEL_PREFIX:-local.my-app}。
default_prefix() {
  _base=$(basename "$PROJECT_ROOT")
  if [ -z "$(printf '%s' "$_base" | LC_ALL=C tr -d '\000-\177')" ]; then
    _slug=$(printf '%s' "$_base" | LC_ALL=C tr '[:upper:]' '[:lower:]' \
      | LC_ALL=C sed -e 's/[^a-z0-9]\{1,\}/-/g' -e 's/^-//' -e 's/-$//')
    case "$_slug" in
      *[a-z0-9]*) printf 'local.%s' "$_slug"; return ;;
    esac
  fi
  printf 'local.p%s' "$(printf '%s' "$PROJECT_ROOT" | cksum | cut -d' ' -f1)"
}
LABEL_PREFIX=${LAUNCHD_LABEL_PREFIX:-$(default_prefix)}

AGENT_DIR=${LAUNCHD_AGENT_DIR:-$HOME/Library/LaunchAgents}
DOMAIN="gui/$(id -u)"

# plist 开头写进这个标记，用来认出是本项目装的、以及它当时的项目根。
OWNER_MARK='<!-- generated by install.sh; project:'

die() {
  printf 'Error: %s\n' "$1" >&2
  exit 1
}

trim() {
  printf '%s' "$1" | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//'
}

require_launchctl() {
  [ "$(uname -s)" = Darwin ] || die 'LaunchAgent 只在 macOS 上可用'
  command -v launchctl >/dev/null 2>&1 || die '找不到 launchctl 命令'
}

# 列出本前缀已装的 plist 路径，每行一个（没有就什么都不输出）
installed_plists() {
  [ -d "$AGENT_DIR" ] || return 0
  find "$AGENT_DIR" -maxdepth 1 -name "$LABEL_PREFIX.*.plist" -type f 2>/dev/null | sort
}

# 装它的项目根；写进 plist 时转义过 XML 实体，这里还原回来，路径里有 & < > 也比得上
plist_owner() {
  sed -n "s|.*${OWNER_MARK} \(.*\) -->.*|\1|p" "$1" 2>/dev/null | head -n 1 \
    | sed -e 's/&lt;/</g' -e 's/&gt;/>/g' -e 's/&amp;/\&/g'
}

label_of() {
  _base=$(basename "$1")
  printf '%s' "${_base%.plist}"
}

# 核对已装的 plist 是不是本项目装的。install / uninstall 都会按前缀删 plist，撞车时会删掉别人的，
# 所以动手之前先查。没有生成标记的（手写的 LaunchAgent 恰好用了同样的前缀）一律报错退出，不碰：
# 它不是本安装器装的，删了不可逆。有标记的看它记着的项目根：与当前不同、且那里仍有 launchd/common.sh
# 就是撞车；那个目录已不存在或已没有 launchd/common.sh 的，当作项目搬走了，由当前项目接管。
check_prefix_owner() {
  _list=$(installed_plists)
  while IFS= read -r _p; do
    [ -n "$_p" ] || continue
    _owner=$(plist_owner "$_p")
    if [ -z "$_owner" ]; then
      die "$_p 用着标签前缀 $LABEL_PREFIX，但不是本安装器装的（没有生成标记）；在 common.sh 里把 LABEL_PREFIX 改掉，或自行处理这个 plist 后再装"
    fi
    if [ "$_owner" = "$PROJECT_ROOT" ] || [ ! -d "$_owner" ]; then
      continue
    fi
    # plist 里记的可能是经软链的路径，按物理路径再比一次。
    if [ "$(CDPATH= cd -- "$_owner" && pwd -P)" = "$PROJECT_ROOT" ]; then
      continue
    fi
    # 不限深度：脚本放得再深也得找到，否则会把仍在用的项目误判为已搬走、删掉它的 plist。
    if [ -n "$(find "$_owner" \( -name node_modules -o -name .git \) -prune -o -path '*/launchd/common.sh' -print 2>/dev/null | head -n 1)" ]; then
      die "标签前缀 $LABEL_PREFIX 已被 $_owner 使用（${_p}），在 common.sh 里把 LABEL_PREFIX 改掉"
    fi
  done <<LIST
$_list
LIST
}

# 卸载并删除本前缀下带生成标记的 plist，把个数写到标准输出。没有标记的不是本安装器装的，
# 跳过不动——调用方都先过 check_prefix_owner，这里只是不把别人的 plist 交给 rm。
remove_all() {
  _removed=0
  _list=$(installed_plists)
  while IFS= read -r _p; do
    [ -n "$_p" ] || continue
    [ -n "$(plist_owner "$_p")" ] || continue
    _label=$(label_of "$_p")
    launchctl bootout "$DOMAIN/$_label" >/dev/null 2>&1 </dev/null || true
    rm -f "$_p"
    _removed=$((_removed + 1))
  done <<LIST
$_list
LIST
  printf '%s' "$_removed"
}
